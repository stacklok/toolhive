// Package controllers contains integration tests for the VirtualMCPServer controller
package controllers

import (
	"time"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	appsv1 "k8s.io/api/apps/v1"
	corev1 "k8s.io/api/core/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/types"

	mcpv1beta1 "github.com/stacklok/toolhive/cmd/thv-operator/api/v1beta1"
	"github.com/stacklok/toolhive/cmd/thv-operator/api/v1beta1/v1beta1test"
	vmcpconfig "github.com/stacklok/toolhive/pkg/vmcp/config"
)

// Reproduces #6837 end to end: with outgoingAuth.source: inline, an MCPServerEntry
// carrying spec.externalAuthConfigRef had its header-injection strategy written
// into the vMCP config while the secret env var that strategy names was left off
// the Deployment, so the pod exited at startup with
// "environment variable TOOLHIVE_HEADER_INJECTION_VALUE_<CONFIG> not set or empty".
var _ = Describe("VirtualMCPServer MCPServerEntry ExternalAuthConfig Integration Tests",
	Label("k8s", "externalauth"), func() {
		const (
			timeout   = time.Second * 30
			interval  = time.Millisecond * 250
			namespace = "default"

			groupName      = "test-group-entry-auth"
			entryName      = "entry-auth-backend"
			authConfigName = "entry-auth-inline"
			secretName     = "entry-auth-secret"
			vmcpName       = "vmcp-entry-auth-inline"

			// Generated by ctrlutil.GenerateUniqueHeaderInjectionEnvVarName from
			// authConfigName; spelled out here to match the runtime lookup the
			// vMCP performs at startup.
			headerInjectionEnvVar = "TOOLHIVE_HEADER_INJECTION_VALUE_ENTRY_AUTH_INLINE"
		)

		Context("When an MCPServerEntry references an MCPExternalAuthConfig and the vMCP uses inline mode",
			Ordered, func() {
				var (
					mcpGroup   *mcpv1beta1.MCPGroup
					entry      *mcpv1beta1.MCPServerEntry
					authConfig *mcpv1beta1.MCPExternalAuthConfig
					vmcp       *mcpv1beta1.VirtualMCPServer
				)

				BeforeAll(func() {
					// Backend discovery resolves the header value from this Secret, so
					// it must exist for the entry to become an accessible backend.
					secret := &corev1.Secret{
						ObjectMeta: metav1.ObjectMeta{Name: secretName, Namespace: namespace},
						StringData: map[string]string{"token": "Bearer test-token"},
					}
					Expect(k8sClient.Create(ctx, secret)).Should(Succeed())

					authConfig = &mcpv1beta1.MCPExternalAuthConfig{
						ObjectMeta: metav1.ObjectMeta{Name: authConfigName, Namespace: namespace},
						Spec: mcpv1beta1.MCPExternalAuthConfigSpec{
							Type: mcpv1beta1.ExternalAuthTypeHeaderInjection,
							HeaderInjection: &mcpv1beta1.HeaderInjectionConfig{
								HeaderName: "Authorization",
								ValueSecretRef: &mcpv1beta1.SecretKeyRef{
									Name: secretName,
									Key:  "token",
								},
							},
						},
					}
					Expect(k8sClient.Create(ctx, authConfig)).Should(Succeed())

					mcpGroup = &mcpv1beta1.MCPGroup{
						ObjectMeta: metav1.ObjectMeta{Name: groupName, Namespace: namespace},
						Spec: mcpv1beta1.MCPGroupSpec{
							Description: "Test group for MCPServerEntry external auth",
						},
					}
					Expect(k8sClient.Create(ctx, mcpGroup)).Should(Succeed())

					entry = &mcpv1beta1.MCPServerEntry{
						ObjectMeta: metav1.ObjectMeta{Name: entryName, Namespace: namespace},
						Spec: mcpv1beta1.MCPServerEntrySpec{
							RemoteURL:             "https://remote.example.com/mcp",
							Transport:             "streamable-http",
							GroupRef:              &mcpv1beta1.MCPGroupRef{Name: groupName},
							ExternalAuthConfigRef: &mcpv1beta1.ExternalAuthConfigRef{Name: authConfigName},
						},
					}
					Expect(k8sClient.Create(ctx, entry)).Should(Succeed())

					// The MCPServerEntry controller is not registered in this suite, so
					// set the phase the backend discoverer requires (it skips entries
					// that are not Valid) by hand.
					entry.Status.Phase = mcpv1beta1.MCPServerEntryPhaseValid
					Expect(k8sClient.Status().Update(ctx, entry)).Should(Succeed())

					// source: inline, and deliberately no entry for this backend under
					// outgoingAuth.backends — the combination that crash-looped.
					vmcp = v1beta1test.NewVirtualMCPServer(vmcpName, namespace,
						v1beta1test.WithVMCPGroupRef(groupName),
						v1beta1test.WithVMCPConfig(vmcpconfig.Config{Group: groupName}),
						v1beta1test.WithVMCPIncomingAuth(&mcpv1beta1.IncomingAuthConfig{
							Type: "anonymous",
						}),
						v1beta1test.WithVMCPOutgoingAuth(&mcpv1beta1.OutgoingAuthConfig{
							Source: "inline",
						}),
					)
					Expect(k8sClient.Create(ctx, vmcp)).Should(Succeed())
				})

				AfterAll(func() {
					_ = k8sClient.Delete(ctx, &corev1.Secret{
						ObjectMeta: metav1.ObjectMeta{Name: secretName, Namespace: namespace},
					})
					_ = k8sClient.Delete(ctx, vmcp)
					_ = k8sClient.Delete(ctx, entry)
					_ = k8sClient.Delete(ctx, mcpGroup)
					_ = k8sClient.Delete(ctx, authConfig)
				})

				It("Should mount the entry's header-injection secret on the vMCP Deployment", func() {
					deployment := &appsv1.Deployment{}
					Eventually(func() error {
						return k8sClient.Get(ctx, types.NamespacedName{
							Name:      vmcpName,
							Namespace: namespace,
						}, deployment)
					}, timeout, interval).Should(Succeed())

					var found *corev1.EnvVar
					Eventually(func() bool {
						if err := k8sClient.Get(ctx, types.NamespacedName{
							Name:      vmcpName,
							Namespace: namespace,
						}, deployment); err != nil {
							return false
						}
						found = nil
						for i := range deployment.Spec.Template.Spec.Containers {
							container := &deployment.Spec.Template.Spec.Containers[i]
							for j := range container.Env {
								if container.Env[j].Name == headerInjectionEnvVar {
									found = &container.Env[j]
									return true
								}
							}
						}
						return false
					}, timeout, interval).Should(BeTrue(),
						"Deployment must carry %s for the MCPServerEntry's ExternalAuthConfig", headerInjectionEnvVar)

					Expect(found.ValueFrom).NotTo(BeNil())
					Expect(found.ValueFrom.SecretKeyRef).NotTo(BeNil())
					Expect(found.ValueFrom.SecretKeyRef.Name).To(Equal(secretName))
					Expect(found.ValueFrom.SecretKeyRef.Key).To(Equal("token"))
				})
			})
	})
